const test = require('node:test')
const assert = require('node:assert/strict')

const agendamentos = require('../src/controllers/agendamentosController')
const criacao = require('../src/controllers/agenda/agendamentosCriacaoController')
const cliente = require('../src/controllers/agenda/agendamentosClienteController')
const admin = require('../src/controllers/agenda/agendamentosAdminController')
const profissional = require('../src/controllers/agenda/agendamentosProfissionalController')
const notificacoes = require('../src/services/notificacoesWhatsappService')
const mensagens = require('../src/services/notificacoesMensagens')
const pagamentos = require('../src/controllers/pagamentosController')
const pagamentosWebhook = require('../src/controllers/pagamentosWebhookController')
const pagamentosCheckout = require('../src/controllers/pagamentosCheckoutController')
const pagamentosDinheiro = require('../src/controllers/pagamentosDinheiroController')
const pagamentosConsulta = require('../src/controllers/pagamentosConsultaController')
const pedidos = require('../src/controllers/pedidosController')
const pedidosCheckout = require('../src/controllers/pedidosCheckoutController')
const pedidosDinheiro = require('../src/controllers/pedidosDinheiroController')
const pedidosCancelamento = require('../src/controllers/pedidosCancelamentoController')
const pedidosConsulta = require('../src/controllers/pedidosConsultaController')
const whatsapp = require('../src/services/whatsappService')
const whatsappUtils = require('../src/services/whatsappUtils')
const disponibilidade = require('../src/controllers/agenda/disponibilidadeController')
const disponibilidadeCalendario = require('../src/controllers/agenda/disponibilidadeCalendarioController')
const disponibilidadeHorarios = require('../src/controllers/agenda/disponibilidadeHorariosController')
const profissionaisAgenda = require('../src/controllers/agenda/profissionaisAgendaController')
const profissionaisHorarios = require('../src/controllers/agenda/profissionaisHorariosController')
const profissionaisAusencias = require('../src/controllers/agenda/profissionaisAusenciasController')

test('fachada de agendamentos preserva os handlers usados pelas rotas', () => {
  assert.equal(agendamentos.criar, criacao.criar)
  assert.equal(agendamentos.listarMeus, cliente.listarMeus)
  assert.equal(agendamentos.cancelar, cliente.cancelar)
  assert.equal(agendamentos.listarAdmin, admin.listarAdmin)
  assert.equal(agendamentos.dashboardAdmin, admin.dashboardAdmin)
  assert.equal(agendamentos.concluirAdmin, admin.concluirAdmin)
  assert.equal(agendamentos.dashboardProfissional, profissional.dashboardProfissional)
})

test('servico de notificacoes preserva os formatadores publicos', () => {
  assert.equal(notificacoes.campoMensagem, mensagens.campoMensagem)
  assert.equal(notificacoes.mensagemConfirmacao, mensagens.mensagemConfirmacao)
  assert.equal(notificacoes.mensagemPedidoConfirmado, mensagens.mensagemPedidoConfirmado)
  assert.equal(typeof notificacoes.criarNotificacoesWhatsappService, 'function')
  assert.equal(typeof notificacoes.obterProcessadorNotificacoesWhatsapp, 'function')
})

test('fachada de pagamentos preserva os handlers usados pelas rotas', () => {
  assert.equal(pagamentos.webhookStripe, pagamentosWebhook.webhookStripe)
  assert.equal(pagamentos.criarCheckout, pagamentosCheckout.criarCheckout)
  assert.equal(pagamentos.registrarPagamentoDinheiro, pagamentosDinheiro.registrarPagamentoDinheiro)
  assert.equal(pagamentos.confirmarPagamentoDinheiro, pagamentosDinheiro.confirmarPagamentoDinheiro)
  assert.equal(pagamentos.consultarCheckout, pagamentosConsulta.consultarCheckout)
})

test('fachada de pedidos preserva os handlers usados pelas rotas', () => {
  assert.equal(pedidos.criarCheckoutProdutos, pedidosCheckout.criarCheckoutProdutos)
  assert.equal(pedidos.reabrirCheckout, pedidosCheckout.reabrirCheckout)
  assert.equal(pedidos.criarPedidoDinheiro, pedidosDinheiro.criarPedidoDinheiro)
  assert.equal(pedidos.cancelarPedido, pedidosCancelamento.cancelarPedido)
  assert.equal(pedidos.listarMeusPedidos, pedidosConsulta.listarMeusPedidos)
})

test('cliente WhatsApp preserva os utilitarios publicos', () => {
  assert.equal(whatsapp.WhatsAppError, whatsappUtils.WhatsAppError)
  assert.equal(whatsapp.normalizarTelefoneBrasil, whatsappUtils.normalizarTelefoneBrasil)
  assert.equal(whatsapp.validarTexto, whatsappUtils.validarTexto)
  assert.equal(whatsapp.extrairTextoMensagem, whatsappUtils.extrairTextoMensagem)
  assert.equal(whatsapp.extrairTelefoneRemetente, whatsappUtils.extrairTelefoneRemetente)
})

test('fachada de disponibilidade preserva os handlers usados pelas rotas', () => {
  assert.equal(disponibilidade.calendarioMensal, disponibilidadeCalendario.calendarioMensal)
  assert.equal(disponibilidade.horariosDisponiveis, disponibilidadeHorarios.horariosDisponiveis)
})

test('fachada da agenda profissional preserva os handlers administrativos', () => {
  assert.equal(profissionaisAgenda.listarHorarios, profissionaisHorarios.listarHorarios)
  assert.equal(profissionaisAgenda.salvarHorarios, profissionaisHorarios.salvarHorarios)
  assert.equal(profissionaisAgenda.listarAusencias, profissionaisAusencias.listarAusencias)
  assert.equal(profissionaisAgenda.criarAusencia, profissionaisAusencias.criarAusencia)
  assert.equal(profissionaisAgenda.deletarAusencia, profissionaisAusencias.deletarAusencia)
  assert.equal(typeof profissionaisAgenda.listarMeusHorarios, 'function')
  assert.equal(typeof profissionaisAgenda.listarMinhasAusencias, 'function')
})
